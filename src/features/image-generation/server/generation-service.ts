// Orchestration only: knowledge → brief → prompts → persisted items. Each item is generated by
// its own request (runItem), so a batch never depends on one long serverless invocation and a
// retry touches only that item.

/**
 * Time budget for all provider calls of one run, below the route's maxDuration (120 s): a hung
 * call is aborted and fails as transient instead of being killed with the function.
 */
export const PROVIDER_BUDGET_MS = 100_000;
/** D8: one automatic retry, only for transient errors and rate limits. */
const AUTO_RETRIES = 1;
/** A retry needs at least this much of the budget left; a real call takes ~15 s. */
const MIN_RETRY_WINDOW_MS = 20_000;
const DAY_MS = 24 * 60 * 60 * 1000;

export async function createSingleBatch(
  ctx: RequestContext,
  request: GenerationRequest,
) {
  const tenant = await ctx.knowledge.getTenant(ctx.tenant.tenantId);
  if (!tenant) throw new NotFoundError(`Unknown tenant ${ctx.tenant.tenantId}`);
  const global = await ctx.knowledge.getGlobal();
  // Throws on unknown IDs or rule conflicts before anything is stored or paid for.
  const brief = buildBrief(global, tenant, request);
  return planBatch(ctx, {
    kind: "single",
    sourceBatchId: null,
    request,
    brief,
    config: ctx.providerConfigFor(brief.format.aspectRatio),
    compose: (variation) => composePrompt(global, brief, variation),
  });
}

/**
 * Screen 2: 15 variations of the user's own successful single generation. They reuse its
 * request, brief, provider snapshot and system instruction — not the current env — so the batch
 * keeps the approved example's settings. Revoked provider settings require a new example.
 */
export async function createVariationsBatch(
  ctx: RequestContext,
  fromBatchId: string,
) {
  const source = await getBatch(ctx, fromBatchId);
  if (source.kind !== "single") {
    throw new InvalidSourceBatchError(
      "Variations can only start from a single generation",
    );
  }
  const example = source.items.find((item) => item.status === "succeeded");
  if (!example) {
    throw new InvalidSourceBatchError(
      "Variations need a successful example image first",
    );
  }
  if (
    !isProviderConfigAllowed(
      example.config,
      ctx.providerConfigFor(example.config.aspectRatio),
    )
  ) {
    throw new InvalidSourceBatchError(
      "The example's provider settings are no longer allowed. Generate a new example first.",
    );
  }
  const global = await ctx.knowledge.getGlobal();
  return planBatch(ctx, {
    kind: "variations",
    sourceBatchId: source.id,
    request: source.request,
    brief: source.brief,
    config: example.config,
    compose: (variation) => ({
      ...composePrompt(global, source.brief, variation),
      systemInstruction: example.prompt.systemInstruction,
    }),
  });
}

/** Options for the generation form: only what the UI shows, never rules or prompt text. */
export async function getFormOptions(
  ctx: RequestContext,
): Promise<FormOptionsView> {
  const tenant = await ctx.knowledge.getTenant(ctx.tenant.tenantId);
  if (!tenant) throw new NotFoundError(`Unknown tenant ${ctx.tenant.tenantId}`);
  const [firstColor] = tenant.palette;
  if (!firstColor)
    throw new Error(`Tenant ${tenant.tenantId} has an empty palette`);
  return {
    brandName: tenant.brandName,
    pages: tenant.pages.map(({ id, url }) => ({ id, url })),
    segments: tenant.segments.map(({ id, label }) => ({ id, label })),
    palette: tenant.palette.map(({ id, name, hex }) => ({ id, name, hex })),
    defaultMainColorId: firstColor.id,
  };
}

export async function getBatch(ctx: RequestContext, batchId: string) {
  const batch = await ctx.repository.getBatch(ctx.tenant.tenantId, batchId);
  if (!batch) throw new NotFoundError(`Batch ${batchId} not found`);
  return batch;
}

/** Runs a queued item or retries a failed one. Idempotent for running/succeeded items. */
export async function runItem(
  ctx: RequestContext,
  batchId: string,
  itemId: string,
  { budgetMs = PROVIDER_BUDGET_MS }: { budgetMs?: number } = {},
): Promise<GenerationItem> {
  const { tenantId } = ctx.tenant;
  const batch = await getBatch(ctx, batchId);
  const current = batch.items.find((item) => item.id === itemId);
  if (!current) throw new NotFoundError(`Item ${itemId} not found in batch`);

  // Only a run that would actually start counts against the daily limit; polling a running or
  // finished item must keep working when the limit is reached.
  if (isClaimable(current)) await assertWithinDailyLimit(ctx);

  const claimed = await ctx.repository.claimItem(tenantId, batchId, itemId);
  // Already running or done: return the current state instead of paying twice.
  if (!claimed) return current;

  const outcome = await generateWithRetry(ctx, claimed, Date.now() + budgetMs);
  if (outcome.kind === "error") {
    // The raw provider message stays in server logs and storage; the browser gets a generic one.
    console.warn(
      `Item ${itemId} attempt ${claimed.attempts} failed (${outcome.error.kind}): ${outcome.error.message}`,
    );
  }
  const saved =
    outcome.kind === "image"
      ? await ctx.repository.completeItem(
          tenantId,
          batchId,
          itemId,
          claimed.attempts,
          {
            mimeType: outcome.image.mimeType,
            data: outcome.image.data,
            model: outcome.image.model,
            providerRequestId: outcome.image.providerRequestId,
            usage: outcome.image.usage,
            durationMs: outcome.durationMs,
          },
        )
      : await ctx.repository.failItem(
          tenantId,
          batchId,
          itemId,
          claimed.attempts,
          // Tenant members can read stored rows; the raw provider text stays in the log above.
          { ...outcome.error, message: publicErrorMessage(outcome.error.kind) },
        );
  // null: a newer attempt took over; its state wins over this late result.
  return (
    saved ??
    (await getBatch(ctx, batchId)).items.find((item) => item.id === itemId) ??
    current
  );
}

function isClaimable(item: GenerationItem, now = Date.now()) {
  return (
    item.status === "queued" ||
    item.status === "failed" ||
    (item.status === "running" &&
      now - Date.parse(item.runningSince) > ITEM_LEASE_MS)
  );
}

async function assertWithinDailyLimit(ctx: RequestContext) {
  const since = new Date(Date.now() - DAY_MS);
  const used = await ctx.repository.countAttemptsSince(
    ctx.tenant.tenantId,
    since,
  );
  if (used >= ctx.dailyAttemptLimit) {
    throw new DailyLimitError(
      `Daily limit of ${ctx.dailyAttemptLimit} generation attempts reached`,
    );
  }
}

export async function getItemImage(ctx: RequestContext, itemId: string) {
  const image = await ctx.repository.getImage(ctx.tenant.tenantId, itemId);
  if (!image) throw new NotFoundError(`Image ${itemId} not found`);
  return image;
}

interface BatchPlan {
  kind: BatchKind;
  sourceBatchId: string | null;
  request: GenerationRequest;
  brief: VisualBrief;
  config: ProviderConfig;
  compose: (variation: Variation) => ComposedPrompt;
}

async function planBatch(
  ctx: RequestContext,
  { kind, sourceBatchId, request, brief, config, compose }: BatchPlan,
) {
  const variations = planVariations(brief, kind === "single" ? 1 : BATCH_SIZE);
  return ctx.repository.createBatch({
    tenantId: ctx.tenant.tenantId,
    kind,
    sourceBatchId,
    request,
    brief,
    items: variations.map((variation) => ({
      variation,
      prompt: compose(variation),
      config,
    })),
  });
}

type Outcome =
  | { kind: "image"; image: GeneratedImage; durationMs: number }
  | { kind: "error"; error: ItemError };

async function generateWithRetry(
  ctx: RequestContext,
  item: RunningItem,
  deadline: number,
): Promise<Outcome> {
  for (let autoRetry = 0; ; autoRetry++) {
    const started = Date.now();
    try {
      if (
        !isProviderConfigAllowed(
          item.config,
          ctx.providerConfigFor(item.config.aspectRatio),
        )
      ) {
        throw new ProviderError(
          "Stored generation settings are not allowed by the current server policy",
          "invalid",
        );
      }
      const provider = ctx.resolveProvider(item.config.provider);
      const image = await provider.generate({
        config: item.config,
        systemInstruction: item.prompt.systemInstruction,
        prompt: item.prompt.prompt,
        idempotencyKey: item.id,
        attempt: item.attempts,
        signal: AbortSignal.timeout(Math.max(1, deadline - Date.now())),
      });
      return { kind: "image", image, durationMs: Date.now() - started };
    } catch (error) {
      const itemError = toItemError(error);
      const timeLeft = deadline - Date.now();
      if (
        !itemError.retryable ||
        autoRetry >= AUTO_RETRIES ||
        timeLeft < MIN_RETRY_WINDOW_MS
      ) {
        return { kind: "error", error: itemError };
      }
    }
  }
}

function toItemError(error: unknown): ItemError {
  if (error instanceof ProviderError) {
    return {
      kind: error.kind,
      message: error.message,
      retryable: error.retryable,
    };
  }
  console.error("Unexpected generation error", error);
  return {
    kind: "invalid",
    message: "Generation failed unexpectedly",
    retryable: false,
  };
}
